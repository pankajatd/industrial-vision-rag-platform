# analyze_predictions.py
"""
Utility script that reads the full predictions CSV generated by evaluate_model.py
and prints a concise summary:
- Overall accuracy
- Confusion matrix (as a pandas DataFrame)
- Number of mis‑classifications and a few example rows
"""

import pandas as pd
from sklearn.metrics import confusion_matrix

CSV_PATH = r"task2_demo_output/predictions_full.csv"

def main():
    df = pd.read_csv(CSV_PATH)
    # Overall accuracy
    accuracy = (df["defect_type"] == df["predicted"]).mean()
    print(f"Overall accuracy: {accuracy:.2%}")

    # Confusion matrix
    labels = sorted(df["defect_type"].unique())
    cm = confusion_matrix(df["defect_type"], df["predicted"], labels=labels)
    cm_df = pd.DataFrame(cm, index=labels, columns=labels)
    print("\nConfusion matrix (rows = true, columns = predicted):")
    print(cm_df)

    # Mis‑classifications
    mis = df[df["defect_type"] != df["predicted"]]
    print(f"\nNumber of mis‑classifications: {len(mis)}")
    if not mis.empty:
        print("Sample mis‑classifications:")
        print(mis[["image_path", "defect_type", "predicted"]].head())

if __name__ == "__main__":
    main()
